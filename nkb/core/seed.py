def demo_brain(path=None, name="neural-kb 示例") -> Brain:
    b = Brain.new(path=path, name=name)
    b.meta.update(demo=True,notice="独立教学示例，不是个人记忆，不可用于真实连接")
    ids = {}
    for label, kind, sal, tags, text in NODES:
        ids[label] = b.add(label, text, kind=kind, tags=tags, salience=sal)
    for a, c, w in EDGES:
        b.link(ids[a], ids[c], w)
    return b
