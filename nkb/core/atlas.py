def atlas_brain(path=None, name="知识星图 · 框架示例") -> Brain:
    b = Brain.new(path=path, name=name)
    b.meta.update({"demo": True, "notice": "全部节点为框架教学知识或虚构测试事件，不是用户个人记忆。"})
    root = b.add("神经记忆网络", "教学图谱：从全局星群放大到任意节点，检查记忆如何关联、淡化、唤醒。所有事件都是明确标记的示例。", id="atlas_root", tags=["框架示例"], salience=.96)
    ids, hubs = {}, []
    for di, (domain, entries) in enumerate(DOMAINS.items()):
        hub = b.add(domain, f"框架示例 · {domain}：包含{len(entries)}个可浏览机制。", id=f"atlas_domain_{di}", tags=[domain, "框架示例"], salience=.9)
        hubs.append(hub)
        b.link(root, hub, .85)
        for ti, (title, explanation) in enumerate(entries):
            prefix = f"atlas_{di}_{ti}"
            term = b.add(title, explanation+"\n\n这是教学知识，不代表真实个人经历。", id=prefix, tags=[domain, "框架示例"], salience=.65+.03*(ti%5))
            q = b.add(f"怎样验证{title}", f"先读取“{title}”的规则：{explanation}\n固定输入、参数和时间，再检查实际节点、边和返回结果；不能仅根据界面动画判定能力存在。", kind="question", id=prefix+"_check", tags=[domain, "验证", "框架示例"], salience=.62)
            a = b.add(f"{title}的接入约定", f"{title}属于{domain}。调用方应保存来源、明确读写意图，并使用同一知识库的真实状态。\n规则依据：{explanation}\n若缺少所需数据，应说明缺失，不能补造记录。", kind="answer", id=prefix+"_use", tags=[domain, "接入", "框架示例"], salience=.64)
            ids[title] = term
            for x,y,w in [(hub,term,.78),(term,q,.65),(term,a,.7),(q,a,.5),(hub,a,.35)]: b.link(x,y,w)
            if ti: b.link(term, f"atlas_{di}_{ti-1}", .35)
    for i, hub in enumerate(hubs): b.link(hub, hubs[(i+1)%len(hubs)], .42)
    for a,c in [("200天恢复窗口","休眠唤醒"),("分级遗忘","状态筛选"),("情绪锚点阈值","事件时间"),("会话边界","锚点前文"),("相近事件桥接","有限记忆片段"),("事实取代","过期桥梁隔离"),("模型替换","结构化记忆"),("只读时间预览","预览不变性"),("幂等衰减","重复维护测试"),("MCP工具","只读召回"),("配置持久化","半衰期"),("来源追溯","不编造经历")]: b.link(ids[a],ids[c],.72)
    ts = now()
    # 两段虚构会话，用来观察锚点前后文；不是对用户经历的推测。
    for group, age in enumerate((2, 160, 210)):
        for i, title in enumerate(("准备出发","开始协作","完成重要里程碑","一起整理资料","记录后续计划","解决第二个难题","收好工作记录","结束这次讨论")):
            nid = b.add(f"示例事件 · {title} {group+1}", f"虚构测试会话{group+1}的第{i+1}条事件，用于验证情绪锚点和时间窗口。它没有在用户生活中真实发生。", kind="episode", id=f"atlas_event_{group}_{i}", tags=["虚构事件", "框架示例"], impact=.86 if i in (2,5) else .12, salience=.6, session_id=f"demo-session-{group}", event_at=ts-age*DAY+i*900, meta={"demo": True, "source": "synthetic-fixture"})
            # 将入库/使用基线放到示例时间，才能看到真实时间投影下的状态。
            n=b.nodes[nid]
            n["created"]=n["reinforced"]=n["decay_at"]=ts-age*DAY+i*900
            b.link(nid, ids["情绪锚点阈值"] if i in (2,5) else ids["分级遗忘"], .36)
            if i: b.link(nid,f"atlas_event_{group}_{i-1}",.5)
    return b
